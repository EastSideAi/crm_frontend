"""Сборка рабочих docx-шаблонов из оригиналов владельца.

Запускается заново при каждой правке документов: `python3 rebuild.py`. Читает
`original/` (файлы владельца, не трогаются), пишет рабочие версии рядом. Поэтому
любую правку вносим ЗДЕСЬ, а не в самом .docx: иначе следующий прогон ее сотрет.

Текст в Word разбит на куски (runs) произвольно — «eastside» и «.study» могут быть
разными элементами, поэтому обычная замена по строке не находит ничего. Работаем
абзацами: находим абзац по его полному тексту, собираем заново из одного run,
сохраняя оформление абзаца (w:pPr) и первого run (w:rPr).

Правки только текстовые: даты и номера превращаются в подставляемые поля, почта
приводится к одной, добавляется пункт про подписание кодом. Паспорт и корр. счет
остаются в документах — решение владельца от 2026-08-06.
"""

import re
import zipfile
from pathlib import Path

TPL = Path(__file__).resolve().parent

PARA = re.compile(r"<w:p\b[^>]*>.*?</w:p>|<w:p\b[^>]*/>", re.S)
TEXT = re.compile(r"<w:t[^>]*>(.*?)</w:t>", re.S)


def esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def ptext(p: str) -> str:
    return "".join(TEXT.findall(p))


def rebuild(p: str, text: str) -> str:
    """Абзац с тем же оформлением, но одним куском текста."""
    ppr = re.search(r"<w:pPr>.*?</w:pPr>", p, re.S)
    rpr = re.search(r"<w:rPr>.*?</w:rPr>", p, re.S)
    open_tag = re.match(r"<w:p\b[^>]*>", p).group(0)
    body = ppr.group(0) if ppr else ""
    body += "<w:r>" + (rpr.group(0) if rpr else "")
    body += '<w:t xml:space="preserve">' + esc(text) + "</w:t></w:r>"
    return open_tag + body + "</w:p>"


class Doc:
    def __init__(self, path: Path):
        self.path = path
        with zipfile.ZipFile(path) as z:
            self.names = z.namelist()
            self.blobs = {n: z.read(n) for n in self.names}
        self.xml = self.blobs["word/document.xml"].decode("utf-8")
        self.log: list[str] = []

    # — поиск —
    def paras(self):
        return list(PARA.finditer(self.xml))

    def find(self, needle: str, exact: bool = False) -> list[re.Match]:
        if exact:
            return [m for m in self.paras() if ptext(m.group(0)).strip() == needle]
        return [m for m in self.paras() if needle in ptext(m.group(0))]

    # — операции —
    def set(self, needle: str, new_text: str, expect: int = 1):
        hits = self.find(needle)
        assert len(hits) == expect, f"{self.path.name}: «{needle}» найдено {len(hits)}, ждали {expect}"
        for m in reversed(hits):
            self.xml = self.xml[: m.start()] + rebuild(m.group(0), new_text) + self.xml[m.end():]
        self.log.append(f"заменен абзац «{needle[:40]}…» → «{new_text[:60]}…»")

    def drop(self, needle: str, expect: int = 1, exact: bool = False):
        hits = self.find(needle, exact=exact)
        assert len(hits) == expect, f"{self.path.name}: «{needle}» найдено {len(hits)}, ждали {expect}"
        for m in reversed(hits):
            self.xml = self.xml[: m.start()] + self.xml[m.end():]
        self.log.append(f"убран абзац «{needle[:60]}…» ({expect} шт.)")

    def after(self, needle: str, texts: list[str], expect: int = 1):
        hits = self.find(needle)
        assert len(hits) == expect, f"{self.path.name}: «{needle}» найдено {len(hits)}, ждали {expect}"
        for m in reversed(hits):
            add = "".join(rebuild(m.group(0), t) for t in texts)
            self.xml = self.xml[: m.end()] + add + self.xml[m.end():]
        self.log.append(f"после «{needle[:40]}…» добавлено абзацев: {len(texts)}")

    def save(self, out: Path):
        self.blobs["word/document.xml"] = self.xml.encode("utf-8")
        with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
            for n in self.names:
                z.writestr(n, self.blobs[n])


