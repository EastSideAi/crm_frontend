def dogovor_html(paras, out: Path):
    import html as _h
    body = []
    for t in paras:
        e = _h.escape(t)
        if t.startswith(("ДОГОВОР", "ПРИЛОЖЕНИЕ")):
            body.append(f"<h1>{e}</h1>")
        elif re.match(r"^\d\.\s+[А-ЯЁ]", t) or t in ("ЗАКАЗЧИК", "ИСПОЛНИТЕЛЬ"):
            body.append(f'<div class="sec">{e}</div>')
        elif re.match(r"^\d+\.\d+", t):
            body.append(f'<p class="i">{e}</p>')
        elif t.startswith(("№", "г. Хабаровск", "к Договору")):
            body.append(f'<div class="sub">{e}</div>')
        elif t.startswith(("ИП ", "ОГРНИП", "ИНН", "Расчетный", "Банк", "Корр", "БИК",
                           "Адрес", "Тел", "Самозанятый", "Паспорт", "Телефон", "___")):
            body.append(f'<p class="sign">{e}</p>')
        else:
            body.append(f"<p>{e}</p>")
    out.write_text(HTML_HEAD + "\n".join(body) + "\n</div></body></html>", encoding="utf-8")


